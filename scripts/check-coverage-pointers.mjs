#!/usr/bin/env node
/*
 * Enforces CONVENTIONS.md's coverage-pointer rule: a source file with no co-located direct test
 * must name, in its header comment, the test file that does cover it — and that file must exist.
 * Mirrors scripts/check-no-play-functions.mjs's file-scanning and exit-code shape.
 */
import { readFileSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { globRealFiles } from "./glob-real-files.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");

const SOURCE_GLOBS = ["src/**/*.{ts,tsx}", "app/**/*.{ts,tsx}"];

/** The suffix set CONVENTIONS.md's test-location table defines, longest first so `.unit.test.ts` wins over `.test.ts`. */
const TEST_SUFFIXES = [
    ".integration.test.ts",
    ".unit.test.tsx",
    ".unit.test.ts",
    ".node.test.ts",
    ".test.tsx",
    ".test.ts",
];

const POINTER_PREFIX = "Covered by:";

/** The documented escape hatch, kept identical to the shape CONVENTIONS.md prints. */
const NOTHING_TO_TEST_PATTERN = /^nothing to test\s*—\s*(\S.*)$/;

const BACKTICKED_PATH_PATTERN = /`([^`]+)`/g;

/*
 * Generated by `pnpm api:generate` and hand-editing it is banned (docs/adr/tech/0005) — a pointer
 * added here would be erased by the next regeneration and fail CI's API-types drift step.
 */
const EXEMPT_FILES = new Set(["src/lib/core/api-contract/generated-types.ts"]);

const EXEMPT_DIR_PREFIXES = ["src/test-utils/"];

const toPosix = (relativePath) => relativePath.split(path.sep).join("/");

/** A test file is any `*.test.*`/`*.spec.*`; a story is a fixture, not an assertion, so it is not one. */
export const isTestPath = (relativePath) => {
    const basename = path.basename(toPosix(relativePath));
    return basename.includes(".test.") || basename.includes(".spec.");
};

const isStoryPath = (relativePath) => path.basename(toPosix(relativePath)).includes(".stories.");

export const isScannedSource = (relativePath) => {
    const posix = toPosix(relativePath);

    if (EXEMPT_FILES.has(posix)) return false;
    if (EXEMPT_DIR_PREFIXES.some((prefix) => posix.startsWith(prefix))) return false;
    if (posix.endsWith(".d.ts")) return false;

    return !isTestPath(posix) && !isStoryPath(posix);
};

/*
 * Each suffix is probed on its own: a single multi-argument existence check reports every file as
 * untested the moment ONE candidate is absent, which is the matcher bug this plan's sizing pass hit.
 */
export const findCoLocatedTests = ({ relativePath, exists }) => {
    const posix = toPosix(relativePath);
    const extension = path.extname(posix);
    const stem = posix.slice(0, posix.length - extension.length);

    return TEST_SUFFIXES.map((suffix) => `${stem}${suffix}`).filter((candidate) => exists(candidate));
};

/*
 * The header region is everything before the first real statement: blank lines, directive
 * prologues (`"use client"`) and comments. A pointer below the first import is not a header
 * comment and does not count, which is the whole point of the rule being readable at a glance.
 */
export const readHeaderComment = ({ source }) => {
    const headerLines = [];
    let isInsideBlock = false;

    for (const line of source.split("\n")) {
        const trimmed = line.trim();

        if (isInsideBlock) {
            headerLines.push(trimmed);
            if (trimmed.includes("*/")) isInsideBlock = false;
            continue;
        }

        if (trimmed === "") continue;

        if (trimmed.startsWith("//")) {
            headerLines.push(trimmed);
            continue;
        }

        if (trimmed.startsWith("/*")) {
            headerLines.push(trimmed);
            if (!trimmed.includes("*/")) isInsideBlock = true;
            continue;
        }

        if (/^["']use (client|server|strict)["'];?$/.test(trimmed)) continue;

        break;
    }

    return headerLines;
};

const extractBacktickedPaths = (text) => [...text.matchAll(BACKTICKED_PATH_PATTERN)].map((match) => match[1].trim());

/*
 * Returns every violation for one file rather than the first: a repository-wide sweep fixed one
 * error per run is how a check gets disabled instead of satisfied.
 */
export const findPointerViolations = ({ relativePath, source, exists }) => {
    const headerLines = readHeaderComment({ source });
    const pointerLine = headerLines.find((line) => line.includes(POINTER_PREFIX));

    if (pointerLine === undefined) {
        return [{ relativePath, kind: "missing", detail: "no `Covered by:` line in the file's header comment" }];
    }

    const remainder = pointerLine.slice(pointerLine.indexOf(POINTER_PREFIX) + POINTER_PREFIX.length).trim();

    if (remainder === "") {
        return [{ relativePath, kind: "empty", detail: "`Covered by:` names nothing" }];
    }

    if (remainder.startsWith("nothing to test")) {
        return !NOTHING_TO_TEST_PATTERN.test(remainder)
            ? [
                  {
                      relativePath,
                      kind: "empty",
                      detail: "the escape hatch needs a reason: `Covered by: nothing to test — <one clause why>`",
                  },
              ]
            : [];
    }

    const citedPaths = extractBacktickedPaths(remainder);

    if (citedPaths.length === 0) {
        return [
            {
                relativePath,
                kind: "unquoted",
                detail: "`Covered by:` must name a repo-relative path in backticks, not a description",
            },
        ];
    }

    return citedPaths.flatMap((citedPath) => {
        if (!exists(citedPath)) {
            return [{ relativePath, kind: "unresolved", detail: `\`${citedPath}\` does not exist` }];
        }

        if (!isTestPath(citedPath)) {
            return [{ relativePath, kind: "not-a-test", detail: `\`${citedPath}\` is not a test file` }];
        }

        return [];
    });
};

const fileExists = (relativePath) => {
    try {
        return statSync(path.resolve(repoRoot, relativePath)).isFile();
    } catch {
        return false;
    }
};

export const scanSources = ({ files, readSource, exists }) =>
    files
        .filter((relativePath) => isScannedSource(relativePath))
        .filter((relativePath) => findCoLocatedTests({ relativePath, exists }).length === 0)
        .flatMap((relativePath) => findPointerViolations({ relativePath, source: readSource(relativePath), exists }))
        .sort((a, b) => a.relativePath.localeCompare(b.relativePath));

const runCli = () => {
    const files = globRealFiles({ patterns: SOURCE_GLOBS, cwd: repoRoot }).map(toPosix);

    const violations = scanSources({
        files,
        readSource: (relativePath) => readFileSync(path.resolve(repoRoot, relativePath), "utf8"),
        exists: fileExists,
    });

    if (violations.length > 0) {
        console.error(
            "coverage:check failed — a source file with no co-located direct test must open with a " +
                "`Covered by:` comment naming the test file that covers it, in backticks, and that file " +
                "must exist. See CONVENTIONS.md, beneath the test-location table.\n",
        );
        for (const violation of violations) {
            console.error(`  ${violation.relativePath} — ${violation.detail}`);
        }
        console.error(`\n${String(violations.length)} violation(s).`);
        process.exit(1);
    }

    console.log(
        `coverage:check passed — every source file without a co-located direct test names one that exists ` +
            `(${String(files.filter(isScannedSource).length)} source files scanned).`,
    );
};

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
    runCli();
}
